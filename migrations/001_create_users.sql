-- Every account: customers, consultants and admins all live here.
-- Roles go in a separate table (next migration), because one user can have many.
CREATE TABLE users (
  id            TEXT    PRIMARY KEY,          -- UUID generated by the app
  email         TEXT    NOT NULL UNIQUE,      -- stored lowercased by the app
  password_hash TEXT    NOT NULL,             -- Argon2id hash, never the password
  name          TEXT    NOT NULL,
  created_at    INTEGER NOT NULL,             -- UTC epoch milliseconds
  updated_at    INTEGER NOT NULL
) STRICT;
